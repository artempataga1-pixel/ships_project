'use client'

import { usePathname } from 'next/navigation'

/* Куда ведут кнопки «Связаться»/«Контакты» из шапки, FAB и нижнего меню.

   На главной — прежний якорь «/#contacts»: блок «Контакты» там на месте,
   клик перехватывает Lenis (или story-контроллер) и плавно долистывает.

   С любой другой страницы якорь означал бы полную загрузку главной со всем
   сторибуком — 9.5 МБ трафика ради формы на пять полей (замер прод-билда).
   Оттуда ведём на отдельную страницу /contacts с тем же блоком.

   ВАЖНО: подменять href можно ТОЛЬКО в момент рендера. В useActiveSection
   обязан уходить исходный NAV_ITEMS — хук ищет секции по id из href
   («/#contacts» → id="contacts"), и «/contacts» без решётки сломал бы
   подсветку активного пункта меню. */
export function useContactsHref(): string {
  return usePathname() === '/' ? '/#contacts' : '/contacts'
}
