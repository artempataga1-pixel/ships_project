/* Рейтинги и регалии — из файла заказчика «Регалии ШиПа (рейтинги).docx»
   (тот же текст, что doks/«Регалии ШиПа.docx»).

   Строки рейтингов разложены на ранг и практику («1 Band» + «Банкротство
   физических лиц»), чтобы ранг можно было показать отдельной плашкой.
   Слова не менялись; выровнен только регистр названий практик, набранных в
   документе капсом, и исправлен пропуск пробела («ТРУДОВОЕИ»). */

export interface RatingEntry {
  /* «1 Band», «3 группа», «Лидеры», «Рекомендованная фирма»; пусто — ранга
     в файле нет, плашка не рисуется */
  rank: string
  practice: string
}

export interface RatingYear {
  /* Год или годы («2020–2022»); пусто — в файле год не указан */
  year: string
  /* Подгруппы внутри года («Отраслевые практики», «Правовые практики») */
  groups: { title?: string; entries: RatingEntry[] }[]
}

export interface RatingSource {
  /* Название — оно же ключ логотипа в MEDIA_MENTIONS, если логотип есть */
  name: string
  years: RatingYear[]
}

