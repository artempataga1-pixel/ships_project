/* Сколько практик отмечено в свежем году рейтинга фирмы */
function latestYearNote(name: string): string {
  const latest = FIRM_RATINGS.find((s) => s.name === name)?.years[0]
  if (!latest) return ''
  const count = latest.groups.reduce((sum, g) => sum + g.entries.length, 0)
  return `В ${latest.year} году отмечены ${pluralPractices(count)}`
}

